import { afterEach, describe, expect, it } from "vitest";
import { eq } from "drizzle-orm";
import type { AgentAccountHome } from "../src/application/agent-accounts/agentAccountHome";
import { SessionAccountGate } from "../src/application/services/terminal/sessionAccountGate";
import { DrizzleAgentAccountDao } from "../src/infra/database/dao/agent-accounts/drizzleAgentAccountDao";
import { agentAccounts, taskAgentAccounts, taskTerminalSessions } from "../src/infra/database/schema";
import { machineIdentity } from "../src/infra/terminal/machineIdentity";
import { ScriptedSessionRuntime } from "../src/infra/terminal/scriptedSessionRuntime";
import { DrizzleSessionHostDao } from "../src/infra/database/dao/terminal/drizzleSessionHostDao";
import { closeTaskFixture } from "./task-api-support";
import { cleanupTerminalFolders } from "./terminal-support";
import { cycle, sendMessage, workerWorld } from "./session-worker-support";
import { seedStoredPlan, seedTaskSet } from "./plan-support";
import { startItem } from "./plan-open-support";

afterEach(async () => { await closeTaskFixture(); await cleanupTerminalFolders(); });

describe("work account session journey", () => {
  it("V-06d and V-10c keep each session's account across a switch and log ids without email", async () => {
    const world = await workerWorld();
    const accounts = new DrizzleAgentAccountDao(world.setup.database);
    const first = await accounts.insert({ ownerUserId: world.setup.ownerId, hostId: machineIdentity(), provider: "claude", label: "Pessoal" });
    const second = await accounts.insert({ ownerUserId: world.setup.ownerId, hostId: machineIdentity(), provider: "claude", label: "Trabalho" });
    await world.setup.database.update(agentAccounts).set({ identity: "ana@example.test" }).where(eq(agentAccounts.id, first.id));
    await world.setup.database.insert(taskAgentAccounts).values({ taskId: world.setup.taskId, provider: "claude", accountId: first.id, chosenBy: world.setup.ownerId, version: 1 });
    const home: AgentAccountHome = { pathOf: ({ id }) => `/accounts/${id}`, ensure: async ({ id }) => `/accounts/${id}`, logoutAndDelete: async () => ({ logout: "ok" }) };
    const gate = new SessionAccountGate({ accounts, home, inspector: { inspect: async () => ({ status: "logged_in", identity: null, plan: null, detail: null }) }, hostId: machineIdentity() });
    world.worker = world.build({ accountGate: gate });
    const firstSession = await world.open();
    await cycle(world);
    expect(world.runtime.starts[0]?.credentialHome).toBe(`/accounts/${first.id}`);
    await sendMessage(world, firstSession, "Continuar");
    await world.setup.client`update task_terminal_sessions set status = 'interrupted', worker_id = 'w-old' where id = ${firstSession}`;
    await world.setup.database.update(taskAgentAccounts).set({ accountId: second.id, version: 2 }).where(eq(taskAgentAccounts.taskId, world.setup.taskId));
    const runtime = new ScriptedSessionRuntime();
    const worker = world.build({ runtimes: { claude: runtime }, workerId: "worker-2", accountGate: gate });
    await worker.supervisor.tick();
    expect(runtime.resumes[0]?.credentialHome).toBe(`/accounts/${first.id}`);
    const secondSession = await world.open({ requestKey: crypto.randomUUID() });
    await worker.supervisor.tick();
    expect(runtime.starts[0]?.credentialHome).toBe(`/accounts/${second.id}`);
    const sessions = await world.setup.database.select().from(taskTerminalSessions).where(eq(taskTerminalSessions.taskId, world.setup.taskId));
    expect(sessions).toHaveLength(2);
    expect(Object.fromEntries(sessions.map((session) => [session.id, session.status]))).toMatchObject({ [firstSession]: "running", [secondSession]: "running" });
    await runtime.runnerOf(secondSession).close();
    await worker.idle();
    const third = await accounts.insert({ ownerUserId: world.setup.ownerId, hostId: machineIdentity(), provider: "claude", label: "Outra" });
    await world.setup.database.update(taskAgentAccounts).set({ accountId: third.id, version: 3 }).where(eq(taskAgentAccounts.taskId, world.setup.taskId));
    const failedSession = await world.open({ requestKey: crypto.randomUUID() });
    await world.setup.database.update(agentAccounts).set({ ownerUserId: world.setup.readerId }).where(eq(agentAccounts.id, third.id));
    await worker.supervisor.tick();
    expect(await world.setup.database.select().from(taskTerminalSessions).where(eq(taskTerminalSessions.id, failedSession))).toMatchObject([{ launchError: "A conta desta sessão não está disponível nesta máquina." }]);
    expect(world.log.entries.find((entry) => entry.event === "started")?.fields).toMatchObject({ account: first.id });
    expect(world.log.entries.find((entry) => entry.event === "resumed")?.fields).toMatchObject({ account: first.id });
    expect(world.log.entries.filter((entry) => entry.event === "launch_failed").at(-1)?.fields).toMatchObject({ account: third.id, reason: "account_rejected" });
    expect(world.log.entries.find((entry) => entry.event === "exited")?.fields).toMatchObject({ account: second.id });
    expect(JSON.stringify(world.log.entries)).not.toContain("ana@example.test");
  });

  it("V-06d starts a plan item with the current Codex account", async () => {
    const status = { available: true, reason: null, version: "0.159.3", refreshedAt: "2026-11-23T14:32:00.000Z", models: [{ id: "gpt-c-1", label: "Codex C", isDefault: true, efforts: ["high"], defaultEffort: "high" }] };
    const world = await workerWorld({}, {}, { codexProbe: { read: async () => status } });
    const hostId = machineIdentity();
    await new DrizzleSessionHostDao(world.setup.database).publishCodexStatus({ hostId, status });
    await seedTaskSet(world, { ids: ["task_01", "task_02"] });
    const choice = { agent: "codex" as const, model: "gpt-c-1", effort: "high" };
    const { items } = await seedStoredPlan(world, { items: [{ taskIds: ["task_01"], choice }, { taskIds: ["task_02"], choice }] });
    const accounts = new DrizzleAgentAccountDao(world.setup.database);
    const accountB = await accounts.insert({ ownerUserId: world.setup.ownerId, hostId, provider: "codex", label: "Codex B" });
    const accountC = await accounts.insert({ ownerUserId: world.setup.ownerId, hostId, provider: "codex", label: "Codex C" });
    await accounts.saveCheck({ id: accountB.id, status: "logged_in", identity: null, plan: null, codexCatalog: status, checkedAt: new Date("2026-11-23T14:32:00.000Z") });
    await accounts.saveCheck({ id: accountC.id, status: "logged_in", identity: null, plan: null, codexCatalog: status, checkedAt: new Date("2026-11-23T14:32:00.000Z") });
    await world.setup.database.insert(taskAgentAccounts).values({ taskId: world.setup.taskId, provider: "codex", accountId: accountB.id, chosenBy: world.setup.ownerId, version: 1 });
    const home: AgentAccountHome = { pathOf: ({ id }) => `/accounts/${id}`, ensure: async ({ id }) => `/accounts/${id}`, logoutAndDelete: async () => ({ logout: "ok" }) };
    const gate = new SessionAccountGate({ accounts, home, inspector: { inspect: async () => ({ status: "logged_in", identity: null, plan: null, detail: null }) }, hostId });
    const runtime = new ScriptedSessionRuntime();
    world.worker = world.build({ runtimes: { codex: runtime }, accountGate: gate });
    const { sessionId } = await startItem(world, { kind: "plan_item", planItemId: items[0]!.id });
    await world.worker.supervisor.tick();
    expect(runtime.starts[0]).toMatchObject({ sessionId, credentialHome: `/accounts/${accountB.id}` });
    await world.setup.database.update(taskAgentAccounts).set({ accountId: accountC.id, version: 2 }).where(eq(taskAgentAccounts.taskId, world.setup.taskId));
    const next = await startItem(world, { kind: "plan_item", planItemId: items[1]!.id });
    await world.worker.supervisor.tick();
    expect(runtime.starts[1]).toMatchObject({ sessionId: next.sessionId, credentialHome: `/accounts/${accountC.id}` });
  });
});
